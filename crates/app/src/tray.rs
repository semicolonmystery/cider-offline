//! System tray icon and menu (`tray-icon` + its `menu`).
//!
//! The icon is created and updated on the main thread on every OS. Creation
//! is deferred until the Slint (winit) event loop runs (required on macOS).
//! On Linux the `ksni` backend speaks `StatusNotifierItem` over D-Bus on its
//! own thread, so there is no GTK; it needs a tray host on the session bus
//! (see `tray_host`).
//!
//! Menu and icon events arrive on arbitrary threads through the global
//! `set_event_handler` hooks and are forwarded as [`TrayAction`]s.

use std::cell::RefCell;

use anyhow::Context as _;
use cider_offline_core::Mode;
use tray_icon::menu::{CheckMenuItem, Menu, MenuEvent, MenuItem, PredefinedMenuItem};
use tray_icon::{Icon, MouseButton, MouseButtonState, TrayIcon, TrayIconBuilder, TrayIconEvent};

/// Raw RGBA icon data generated by `build.rs`.
struct RawIcon {
    rgba: &'static [u8],
    width: u32,
    height: u32,
}

include!(concat!(env!("OUT_DIR"), "/tray_icons.rs"));

const ID_PASSTHROUGH: &str = "passthrough";
const ID_CAPTURE: &str = "capture";
const ID_OPEN: &str = "open";
const ID_QUIT: &str = "quit";

/// A user action in the tray.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum TrayAction {
    /// The Passthrough check item was clicked.
    TogglePassthrough,
    /// The Capture check item was clicked.
    ToggleCapture,
    /// "Open window" or a left click on the icon.
    OpenWindow,
    /// "Quit".
    Quit,
}

/// Proxy reachability shown in the tray.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum Connection {
    /// The proxy is not running.
    Stopped,
    /// Running, Apple Music reachable.
    Online,
    /// Running, Apple Music unreachable (serving from cache).
    Offline,
}

/// What the tray displays.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct TrayState {
    /// Proxy mode.
    pub mode: Mode,
    /// Capture-to-disk enabled.
    pub capture: bool,
    /// Proxy / network state.
    pub connection: Connection,
    /// Proxy address, e.g. `127.0.0.1:8000`.
    pub address: String,
}

impl TrayState {
    /// One-line status used for the tooltip and the disabled status item.
    pub fn status_line(&self) -> String {
        let net = match self.connection {
            Connection::Stopped => return "Proxy stopped".to_owned(),
            Connection::Online => "online",
            Connection::Offline => "offline",
        };
        let mode = match self.mode {
            Mode::Active => "Active",
            Mode::Passthrough => "Passthrough",
        };
        format!("{mode} · {net} · {}", self.address)
    }
}

/// Installs the process-wide tray/menu event handlers. Call once.
pub fn set_event_handler(on_action: impl Fn(TrayAction) + Send + Sync + Clone + 'static) {
    let on_menu = on_action.clone();
    MenuEvent::set_event_handler(Some(move |event: MenuEvent| {
        let action = match event.id().as_ref() {
            ID_PASSTHROUGH => TrayAction::TogglePassthrough,
            ID_CAPTURE => TrayAction::ToggleCapture,
            ID_OPEN => TrayAction::OpenWindow,
            ID_QUIT => TrayAction::Quit,
            _ => return,
        };
        on_menu(action);
    }));
    TrayIconEvent::set_event_handler(Some(move |event: TrayIconEvent| {
        if LEFT_CLICK_OPENS_WINDOW && let Some(action) = icon_action(&event) {
            on_action(action);
        }
    }));
}

/// Whether a left click on the icon opens the window instead of the menu.
///
/// Windows and Linux: there the menu belongs to the right click (the `ksni`
/// backend emits left-click activations). macOS menu-bar items conventionally
/// open their menu on left click.
const LEFT_CLICK_OPENS_WINDOW: bool = cfg!(any(windows, target_os = "linux"));

/// Maps a raw icon event to an action (the menu is shown natively).
///
/// Only the left button's release counts. A press would fire a second time
/// for the same click, and a Windows double click already arrives as
/// down/up/double-click/up, i.e. as two releases; opening the window is
/// idempotent, so the `DoubleClick` event itself is ignored.
fn icon_action(event: &TrayIconEvent) -> Option<TrayAction> {
    match event {
        TrayIconEvent::Click {
            button: MouseButton::Left,
            button_state: MouseButtonState::Up,
            ..
        } => Some(TrayAction::OpenWindow),
        _ => None,
    }
}

/// The native tray icon with its menu items.
struct TrayItems {
    icon: TrayIcon,
    status: MenuItem,
    passthrough: CheckMenuItem,
    capture: CheckMenuItem,
    shown: Option<TrayState>,
}

impl TrayItems {
    fn build(state: &TrayState) -> anyhow::Result<Self> {
        let status = MenuItem::new(state.status_line(), false, None);
        let passthrough = CheckMenuItem::with_id(
            ID_PASSTHROUGH,
            "Passthrough",
            true,
            state.mode == Mode::Passthrough,
            None,
        );
        let capture = CheckMenuItem::with_id(ID_CAPTURE, "Capture", true, state.capture, None);
        let open = MenuItem::with_id(ID_OPEN, "Open window", true, None);
        let quit = MenuItem::with_id(ID_QUIT, "Quit", true, None);
        let menu = Menu::with_items(&[
            &status,
            &PredefinedMenuItem::separator(),
            &passthrough,
            &capture,
            &PredefinedMenuItem::separator(),
            &open,
            &quit,
        ])
        .context("building the tray menu")?;

        let builder = TrayIconBuilder::new()
            .with_menu(Box::new(menu))
            // tray-icon defaults to showing the menu on left click too (it
            // pops up right after the click event is sent), which flashed
            // the menu whenever a left click opened the window.
            .with_menu_on_left_click(!LEFT_CLICK_OPENS_WINDOW)
            .with_tooltip(tooltip(state));
        let icon = with_mode_icon(builder, mode_icon(state.mode)?)
            .build()
            .context("creating the tray icon")?;
        Ok(Self {
            icon,
            status,
            passthrough,
            capture,
            shown: Some(state.clone()),
        })
    }

    /// Updates only what changed since the last call.
    fn apply(&mut self, state: &TrayState) {
        let previous = self.shown.replace(state.clone());
        let previous = previous.as_ref();
        // Check items toggle themselves when clicked; always re-assert the
        // authoritative state.
        self.passthrough
            .set_checked(state.mode == Mode::Passthrough);
        self.capture.set_checked(state.capture);
        if previous.map(TrayState::status_line) != Some(state.status_line()) {
            self.status.set_text(state.status_line());
            if let Err(error) = self.icon.set_tooltip(Some(tooltip(state))) {
                tracing::debug!(%error, "could not set the tray tooltip");
            }
        }
        if previous.map(|p| p.mode) != Some(state.mode) {
            match mode_icon(state.mode) {
                Ok(icon) => {
                    if let Err(error) = set_mode_icon(&self.icon, icon) {
                        tracing::warn!(%error, "could not change the tray icon");
                    }
                }
                Err(error) => tracing::warn!(%error, "invalid tray icon"),
            }
        }
    }
}

fn tooltip(state: &TrayState) -> String {
    format!("Cider Offline\n{}", state.status_line())
}

fn mode_icon(mode: Mode) -> anyhow::Result<Icon> {
    // macOS: black glyph template images (Passthrough at half opacity);
    // elsewhere the full-colour tile icons.
    #[cfg(target_os = "macos")]
    let raw = match mode {
        Mode::Active => &TRAY_TEMPLATE,
        Mode::Passthrough => &TRAY_TEMPLATE_PASSTHROUGH,
    };
    #[cfg(not(target_os = "macos"))]
    let raw = match mode {
        Mode::Active => &TRAY_ACTIVE,
        Mode::Passthrough => &TRAY_PASSTHROUGH,
    };
    Icon::from_rgba(raw.rgba.to_vec(), raw.width, raw.height).context("decoding the tray icon")
}

/// Sets the initial icon; a template image on macOS.
fn with_mode_icon(builder: TrayIconBuilder, icon: Icon) -> TrayIconBuilder {
    #[cfg(target_os = "macos")]
    {
        builder.with_icon_templated(icon)
    }
    #[cfg(not(target_os = "macos"))]
    {
        builder.with_icon(icon)
    }
}

/// Replaces the icon; a template image on macOS.
fn set_mode_icon(tray: &TrayIcon, icon: Icon) -> tray_icon::Result<()> {
    #[cfg(target_os = "macos")]
    {
        tray.set_icon_templated(Some(icon))
    }
    #[cfg(not(target_os = "macos"))]
    {
        tray.set_icon(Some(icon))
    }
}

/// The tray icon, owned by the main thread on every OS.
pub struct Tray {
    items: RefCell<TrayItems>,
}

impl Tray {
    /// Creates the icon. Must run on the main thread while the event loop
    /// is running (e.g. from `slint::invoke_from_event_loop`).
    pub fn create(state: &TrayState) -> anyhow::Result<Self> {
        Ok(Self {
            items: RefCell::new(TrayItems::build(state)?),
        })
    }

    /// Shows `state` in the tray.
    pub fn update(&self, state: &TrayState) {
        self.items.borrow_mut().apply(state);
    }
}

#[cfg(test)]
mod tests {
    use tray_icon::dpi::PhysicalPosition;
    use tray_icon::{Rect, TrayIconId};

    use super::*;

    fn state() -> TrayState {
        TrayState {
            mode: Mode::Active,
            capture: false,
            connection: Connection::Offline,
            address: "127.0.0.1:8000".to_owned(),
        }
    }

    #[test]
    fn status_line_should_show_mode_network_and_address() {
        assert_eq!(state().status_line(), "Active · offline · 127.0.0.1:8000");
    }

    #[test]
    fn status_line_should_report_stopped_proxy() {
        let stopped = TrayState {
            connection: Connection::Stopped,
            ..state()
        };
        assert_eq!(stopped.status_line(), "Proxy stopped");
    }

    fn click(button: MouseButton, button_state: MouseButtonState) -> TrayIconEvent {
        TrayIconEvent::Click {
            id: TrayIconId::new("test"),
            position: PhysicalPosition::default(),
            rect: Rect::default(),
            button,
            button_state,
        }
    }

    #[test]
    fn icon_action_should_open_window_on_left_release() {
        let event = click(MouseButton::Left, MouseButtonState::Up);
        assert_eq!(icon_action(&event), Some(TrayAction::OpenWindow));
    }

    #[test]
    fn icon_action_should_ignore_left_press() {
        let event = click(MouseButton::Left, MouseButtonState::Down);
        assert_eq!(icon_action(&event), None);
    }

    #[test]
    fn icon_action_should_leave_right_click_to_the_menu() {
        for state in [MouseButtonState::Down, MouseButtonState::Up] {
            assert_eq!(icon_action(&click(MouseButton::Right, state)), None);
        }
    }

    #[test]
    fn icon_action_should_ignore_double_click() {
        let event = TrayIconEvent::DoubleClick {
            id: TrayIconId::new("test"),
            position: PhysicalPosition::default(),
            rect: Rect::default(),
            button: MouseButton::Left,
        };
        assert_eq!(icon_action(&event), None);
    }

    #[cfg(not(target_os = "macos"))]
    #[test]
    fn embedded_icons_should_match_their_dimensions() {
        for raw in [&TRAY_ACTIVE, &TRAY_PASSTHROUGH] {
            assert_eq!(raw.rgba.len(), (raw.width * raw.height * 4) as usize);
        }
    }

    #[cfg(target_os = "macos")]
    #[test]
    fn template_icons_should_match_their_dimensions() {
        for raw in [&TRAY_TEMPLATE, &TRAY_TEMPLATE_PASSTHROUGH] {
            assert_eq!(raw.rgba.len(), (raw.width * raw.height * 4) as usize);
        }
    }
}
